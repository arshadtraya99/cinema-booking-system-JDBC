CREATE DATABASE IF NOT EXISTS Cinema_booking_System;

use Cinema_booking_System;

CREATE TABLE THEATRES (
    THEATRE_ID INT AUTO_INCREMENT PRIMARY KEY,
    THEATRE_NAME VARCHAR(50) NOT NULL,
    LOCATION VARCHAR(50),
    CITY VARCHAR(50) NOT NULL
);

CREATE TABLE Screens (
    screen_id INT AUTO_INCREMENT PRIMARY KEY,
    THEATRE_ID INT ,
    SCREEN_NAME VARCHAR(50) NOT NULL,
    TOTAL_SEATS INT NOT NULL,

    FOREIGN KEY(THEATRE_ID) REFERENCES THEATRES(THEATRE_ID) ON DELETE CASCADE
);

CREATE TABLE MOVIES (
    MOVIE_ID INT AUTO_INCREMENT PRIMARY KEY,
    TITLE VARCHAR(100) NOT NULL,
    DURATION FLOAT,
    GENRE VARCHAR(100)
);
CREATE TABLE SHOWS (
    SHOW_ID INT AUTO_INCREMENT PRIMARY KEY,
    MOVIE_ID INT,
    SCREEN_ID INT ,
    show_time TIME,
    SHOW_DATE DATE,

    FOREIGN KEY(MOVIE_ID) REFERENCES MOVIES(MOVIE_ID) ON DELETE CASCADE,
    FOREIGN KEY(SCREEN_ID) REFERENCES SCREENS(SCREEN_ID) ON DELETE CASCADE,
    UNIQUE (SCREEN_ID, SHOW_DATE, show_time)
);
CREATE TABLE SEAT_CATEGORY (
    CATEGORY_ID INT AUTO_INCREMENT PRIMARY KEY,
    CATEGORY_NAME VARCHAR(50) NOT NULL,
    PRICE DECIMAL(10 , 2)
);
CREATE TABLE SEATS (
    SEAT_ID INT PRIMARY KEY AUTO_INCREMENT,
    SHOW_ID INT NOT NULL,
    CATEGORY_ID INT,
    SEAT_ROW VARCHAR(10) NOT NULL,
    `NUMBER` INT NOT NULL,
    ISBOOKED BOOLEAN NOT NULL DEFAULT FALSE,

    FOREIGN KEY(SHOW_ID) REFERENCES SHOWS(SHOW_ID) ON DELETE CASCADE,
    FOREIGN KEY(CATEGORY_ID) REFERENCES SEAT_CATEGORY(CATEGORY_ID),
    UNIQUE (SHOW_ID, SEAT_ROW, `NUMBER`),
    UNIQUE (SHOW_ID, SEAT_ID)
);
CREATE TABLE USERS (
    USER_ID INT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(100) NOT NULL,
    USERNAME VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR(100) NOT NULL,
    ROLE ENUM('ADMIN' , 'CLERK') NOT NULL DEFAULT 'CLERK'
);
CREATE TABLE BOOKINGS (
    BOOKING_ID INT AUTO_INCREMENT PRIMARY KEY,
    SHOW_ID INT NOT NULL,
    SEAT_ID INT NOT NULL,
    CLERK_ID INT NOT NULL,
    CUSTOMER_NAME VARCHAR(100) NOT NULL,
    TOTAL_AMOUNT DECIMAL(10,2) NOT NULL,
    BOOKING_TIME DATETIME DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_booking_show_seat
        FOREIGN KEY (SHOW_ID, SEAT_ID)
        REFERENCES SEATS(SHOW_ID, SEAT_ID)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT fk_booking_clerk
        FOREIGN KEY (CLERK_ID)
        REFERENCES USERS(USER_ID)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT unique_seat_booking
        UNIQUE (SEAT_ID)
);
